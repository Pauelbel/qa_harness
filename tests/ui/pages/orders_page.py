"""Страница «Заказы»."""

from qa.base.report import step
from qa.layers.ui import BasePage

# ------------------------------------------------------------------------
# Локаторы: адрес раздела, строка заказа и её статус
# ------------------------------------------------------------------------

ORDERS_PATH = "/orders"
ORDER_ROW = "//tr[contains(., '{title}')]"  # строка таблицы заказов с этим названием
ROW_STATUS = "[data-testid='order-status']"


# ------------------------------------------------------------------------
# Страница заказов: открытие по адресу и проверки строки заказа
# ------------------------------------------------------------------------

class OrdersPage(BasePage):
    # ------------------------------------------------------------------------
    # Действия: адрес считается от ui_base_url
    # ------------------------------------------------------------------------

    @step("Открыть раздел «Заказы»")
    def open_orders(self):
        self.open(ORDERS_PATH)

    # ------------------------------------------------------------------------
    # Проверки: expect ждёт появления строки и нужного статуса в ней
    # ------------------------------------------------------------------------

    @step("Заказ {title} есть в списке со статусом {status}")
    def check_order_status(self, title: str, status: str):
        row = self.page.locator(ORDER_ROW.format(title=title))
        self.element(f"Строка заказа «{title}»", row).check_visible()
        self.element(f"Статус заказа «{title}»", row.locator(ROW_STATUS)).check_have_text(status)
